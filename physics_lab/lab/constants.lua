--------------------------------------------------------------------------------
-- Доступ
--------------------------------------------------------------------------------

--- Численное значение константы по имени: constants.value("g0").
function M.value(name)
	local entry = M.PHYSICAL[name] or M.GAME[name]

	if not entry then
		error("нет такой константы: " .. tostring(name), 2)
	end

	return entry.value
end

--- Та же константа как размерная величина, для проверки формул.
function M.quantity(name)
	local entry = M.PHYSICAL[name] or M.GAME[name]

	if not entry then
		error("нет такой константы: " .. tostring(name), 2)
	end

	return U.Q(entry.value, entry.dim)
end

--- Печатает таблицу констант с обоснованиями.
function M.print()
	local function section(title, table_)
		print(title)

		local names = {}

		for name in pairs(table_) do
			names[#names + 1] = name
		end

		table.sort(names)

		for _, name in ipairs(names) do
			local entry = table_[name]

			print(("  %-22s %-14s [%s]%s")
				:format(name, ("%.6g"):format(entry.value),
					tostring(entry.dim),
					entry.tuning and "  ← настройка" or ""))

			if entry.note then
				print("      " .. entry.note)
			end

			if entry.ref then
				print("      источник: " .. entry.ref.url)
			end
		end
	end

	section("Физические константы:", M.PHYSICAL)
	print()
	section("Параметры игры:", M.GAME)
end

return M
