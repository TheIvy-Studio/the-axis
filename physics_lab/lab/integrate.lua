--- Интегрирует систему фиксированным шагом.
---
--- @param options.method имя схемы
--- @param options.accel  функция ускорения a(x, v, t) -> vec3
--- @param options.x0     начальное положение (vec3)
--- @param options.v0     начальная скорость (vec3)
--- @param options.dt     шаг, с
--- @param options.duration длительность, с
--- @param options.sample  необязательный колбэк sample(t, x, v, step)
--- @return конечное состояние, число шагов, число вызовов ускорения,
---         фактический шаг (может чуть отличаться от options.dt, см. ниже)
function M.simulate(options)
	local method = M.by_key(options.method)
	local accel = options.accel

	local calls = 0

	local counted = function(x, v, t)
		calls = calls + 1
		return accel(x, v, t)
	end

	local state = {
		x = options.x0 or vec3.zero,
		v = options.v0 or vec3.zero,
	}

	-- Число шагов округляется, а шаг подгоняется под него, чтобы конечная
	-- точка попала РОВНО в options.duration. Иначе симуляция заканчивается
	-- на долю шага раньше или позже, аналитическое решение считается для
	-- другого момента времени, и расхождение принимают за ошибку схемы.
	local steps = math.max(1, math.floor(options.duration / options.dt + 0.5))
	local dt = options.duration / steps

	if options.sample then
		options.sample(0, state.x, state.v, 0)
	end

	for step = 1, steps do
		state = method.step(state, counted, dt, (step - 1) * dt)

		if options.sample then
			options.sample(step * dt, state.x, state.v, step)
		end
	end

	return state, steps, calls, dt
end

--------------------------------------------------------------------------------
-- Фиксированный шаг при плавающем кадре
--------------------------------------------------------------------------------
--
-- Практический приём: физика считается всегда одним и тем же dt, а разница
-- между кадром и шагом копится в накопителе. Кадр может быть каким угодно —
-- траектория от этого не меняется. [gaffer_integration]
--
-- Остаток накопителя (alpha) отдаётся наружу для интерполяции при отрисовке:
-- без неё картинка дёргается, потому что состояние обновляется реже кадров.
--------------------------------------------------------------------------------
function M.make_fixed_stepper(options)
	local method = M.by_key(options.method)
	local fixed_dt = options.fixed_dt
	local max_steps = options.max_steps or 8

	local state = {
		x = options.x0 or vec3.zero,
		v = options.v0 or vec3.zero,
	}

	local previous = { x = state.x, v = state.v }
	local accumulator = 0
	local time = 0

	return {
		--- Продвигает симуляцию на длительность кадра.
		--- @return alpha — доля от 0 до 1 для интерполяции между previous и state
		advance = function(frame_dt)
			accumulator = accumulator + frame_dt

			local performed = 0

			while accumulator >= fixed_dt and performed < max_steps do
				previous = state
				state = method.step(state, options.accel, fixed_dt, time)
				time = time + fixed_dt
				accumulator = accumulator - fixed_dt
				performed = performed + 1
			end

			-- Защита от спирали смерти: если кадр настолько длинный, что
			-- шагов не хватило, лишнее время выбрасывается. Симуляция
			-- отстанет от реального времени, но не свалится в лавину.
			if performed >= max_steps then
				accumulator = 0
			end

			return accumulator / fixed_dt, performed
		end,

		state = function() return state end,
		previous = function() return previous end,
		time = function() return time end,
	}
end

return M
