M.methods = {
	{ key = "euler",     label = "Явный Эйлер",        order = 1, step = M.euler_explicit,      evaluations = 1, symplectic = false },
	{ key = "symplectic", label = "Полунеявный Эйлер", order = 1, step = M.euler_semi_implicit, evaluations = 1, symplectic = true },
	{ key = "verlet",    label = "Скоростной Верле",   order = 2, step = M.verlet,              evaluations = 1, symplectic = true },
	{ key = "rk4",       label = "Рунге — Кутта 4",    order = 4, step = M.rk4,                 evaluations = 4, symplectic = false },
}

function M.by_key(key)
	for _, method in ipairs(M.methods) do
		if method.key == key then
			return method
		end
	end

	error("нет такого метода интегрирования: " .. tostring(key), 2)
end

