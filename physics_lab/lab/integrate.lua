-- the Axis · physics lab
-- Численное интегрирование уравнений движения.
--
-- Задача всюду одна и та же: обыкновенное дифференциальное уравнение второго
-- порядка, записанное как система первого порядка
--
--     dx/dt = v
--     dv/dt = a(x, v, t)
--
-- где a — ускорение, м/с^2. Функция ускорения получает положение, скорость и
-- время и обязана быть чистой: интеграторы высокого порядка вызывают её по
-- нескольку раз за шаг в промежуточных точках, и побочные эффекты ломают
-- порядок точности молча, без единого сообщения об ошибке.
--
-- Реализованы четыре схемы. Выбор между ними — не вкусовщина, у каждой свои
-- порядок точности, устойчивость и поведение энергии; всё это измеряется в
-- experiments/16_integration_methods.lua и 17_numerical_stability.lua.
--
-- Источники: [hairer_odes] (порядок и устойчивость), [hairer_geometric]
-- (симплектичность и энергия), [verlet_1967], [swope_1982].

local vec3 = require("lab.vec3")

local M = {}

--------------------------------------------------------------------------------
-- Явный (прямой) метод Эйлера
--------------------------------------------------------------------------------
--
--     x[n+1] = x[n] + v[n] * dt
--     v[n+1] = v[n] + a(x[n], v[n], t) * dt
--
-- Порядок точности: 1 (локальная ошибка O(dt^2), глобальная O(dt)).
-- Устойчивость: условная и плохая. Для гармонического осциллятора энергия
-- растёт при любом dt > 0, то есть схема безусловно неустойчива на колебаниях.
-- Именно поэтому в играх её не применяют, хотя она и напрашивается первой.
--
-- Важная деталь: положение обновляется по СТАРОЙ скорости. Разница с
-- полунеявной схемой ровно в одной строке, а поведение отличается
-- принципиально.
--------------------------------------------------------------------------------
function M.euler_explicit(state, accel, dt, t)
	local a = accel(state.x, state.v, t or 0)

	return {
		x = state.x + state.v * dt,
		v = state.v + a * dt,
	}
end

--------------------------------------------------------------------------------
-- Полунеявный (симплектический) метод Эйлера
--------------------------------------------------------------------------------
--
--     v[n+1] = v[n] + a(x[n], v[n], t) * dt
--     x[n+1] = x[n] + v[n+1] * dt          ← новая скорость, не старая
--
-- Порядок точности: 1, как и у явного. Но схема симплектическая: она точно
-- решает слегка изменённую задачу с близким гамильтонианом, поэтому ошибка
-- энергии колеблется в узкой полосе и не накапливается [hairer_geometric].
-- При той же цене это делает её пригодной там, где явный Эйлер разваливается.
--
-- Это рабочая лошадь игровой физики: одно вычисление ускорения на шаг,
-- устойчивое поведение на пружинах и гравитации, тривиальная реализация.
--------------------------------------------------------------------------------
function M.euler_semi_implicit(state, accel, dt, t)
	local a = accel(state.x, state.v, t or 0)
	local v = state.v + a * dt

	return {
		x = state.x + v * dt,
		v = v,
	}
end

--------------------------------------------------------------------------------
-- Скоростная схема Верле
--------------------------------------------------------------------------------
--
--     x[n+1] = x[n] + v[n]*dt + 0.5*a[n]*dt^2
--     a[n+1] = a(x[n+1], v_pred, t+dt)
--     v[n+1] = v[n] + 0.5*(a[n] + a[n+1])*dt
--
-- Порядок точности: 2, симплектическая, обратимая по времени.
-- [verlet_1967], [swope_1982]
--
-- Сила, зависящая от скорости. Как только появляется сопротивление воздуха
-- a(v), последняя строка становится неявной: чтобы посчитать a[n+1], нужна
-- v[n+1], которой ещё нет. Здесь взят стандартный явный обход — в a[n+1]
-- подставляется предсказанная скорость v_pred = v[n] + a[n]*dt.
--
-- ВАЖНО, и это проверено измерением, а не рассуждением. Изначально здесь
-- стояло утверждение, что схема из-за такой подстановки опускается до
-- первого порядка. Эксперимент 16 его ОПРОВЕРГ: измеренный порядок остаётся
-- равным 2.00 и с вязкостью. Причина видна из разложения: ошибка предсказания
-- скорости сама порядка dt^2, а входит она в член, уже умноженный на dt/2,
-- значит вклад в локальную ошибку O(dt^3) — ровно то, что нужно для второго
-- порядка.
--
-- Что при этом действительно теряется — не порядок, а симплектичность и
-- обратимость по времени. Но для диссипативной системы они и не определены:
-- система с трением не гамильтонова.
--
-- Это ровно тот случай, ради которого лаборатория и строится: правдоподобное
-- рассуждение оказалось неверным, и поймал это тест, а не вычитка.
--------------------------------------------------------------------------------
function M.verlet(state, accel, dt, t)
	t = t or 0

	local a0 = state.a or accel(state.x, state.v, t)
	local x = state.x + state.v * dt + a0 * (0.5 * dt * dt)

	-- Предсказание скорости для сил, зависящих от неё
	local v_predicted = state.v + a0 * dt
	local a1 = accel(x, v_predicted, t + dt)

	return {
		x = x,
		v = state.v + (a0 + a1) * (0.5 * dt),
		-- Ускорение переносится на следующий шаг: без этого схема считает
		-- силу дважды за шаг и теряет и скорость, и точность.
		a = a1,
	}
end

--------------------------------------------------------------------------------
-- Классический метод Рунге — Кутты 4-го порядка
--------------------------------------------------------------------------------
--
-- Таблица Бутчера: c = (0, 1/2, 1/2, 1), веса (1/6, 1/3, 1/3, 1/6).
-- [hairer_odes]
--
-- Порядок точности: 4. Четыре вычисления ускорения на шаг.
-- Схема НЕ симплектическая: на замкнутой орбите энергия медленно уползает
-- (обычно вниз), зато на коротких интервалах точность несравнимо выше.
--
-- Для чего он в этом проекте: не для игры, а как эталон. Прогон РК4 с очень
-- малым шагом даёт «почти точное» решение там, где аналитического нет, и
-- ошибки дешёвых схем меряются относительно него.
--------------------------------------------------------------------------------
function M.rk4(state, accel, dt, t)
	t = t or 0

	local x0, v0 = state.x, state.v

	local k1x = v0
	local k1v = accel(x0, v0, t)

	local k2x = v0 + k1v * (dt * 0.5)
	local k2v = accel(x0 + k1x * (dt * 0.5), v0 + k1v * (dt * 0.5), t + dt * 0.5)

	local k3x = v0 + k2v * (dt * 0.5)
	local k3v = accel(x0 + k2x * (dt * 0.5), v0 + k2v * (dt * 0.5), t + dt * 0.5)

	local k4x = v0 + k3v * dt
	local k4v = accel(x0 + k3x * dt, v0 + k3v * dt, t + dt)

	local sixth = dt / 6

	return {
		x = x0 + (k1x + k2x * 2 + k3x * 2 + k4x) * sixth,
		v = v0 + (k1v + k2v * 2 + k3v * 2 + k4v) * sixth,
	}
end

--------------------------------------------------------------------------------
-- РК4 для системы ПЕРВОГО порядка
--------------------------------------------------------------------------------
--
--     dy/dt = f(y, t)
--
-- Нужен там, где состояние не разбивается на «положение и скорость»: угловая
-- скорость в уравнениях Эйлера подчиняется уравнению первого порядка, и
-- загонять её в схему для второго порядка было бы подгонкой под инструмент.
--------------------------------------------------------------------------------
function M.rk4_first_order(y, derivative, dt, t)
	t = t or 0

	local k1 = derivative(y, t)
	local k2 = derivative(y + k1 * (dt * 0.5), t + dt * 0.5)
	local k3 = derivative(y + k2 * (dt * 0.5), t + dt * 0.5)
	local k4 = derivative(y + k3 * dt, t + dt)

	return y + (k1 + k2 * 2 + k3 * 2 + k4) * (dt / 6)
end

