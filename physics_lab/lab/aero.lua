-- the Axis · physics lab
-- Аэродинамика: скоростной напор, сопротивление, подъёмная сила, разворот.
--
-- Каждая функция снабжена: формулой, единицами, источником, допущениями и
-- границами применимости. Проверка размерностей — не комментарий, а код:
-- функция `dimension_selftest` ниже прогоняет те же выражения на размерных
-- величинах, и несогласованность падает с ошибкой.

local U = require("lab.units")
local C = require("lab.constants")
local R = require("lab.references")

local M = {}

local D = U.D

--------------------------------------------------------------------------------
-- Скоростной напор
--------------------------------------------------------------------------------
--
--     q = 0.5 * rho * V^2                                        [Па]
--
-- Единицы: rho [кг/м^3], V [м/с] → q [кг/(м·с^2)] = [Па]. Сходится.
--
-- Смысл: кинетическая энергия единицы объёма набегающего потока. И
-- сопротивление, и подъёмная сила — это q, умноженное на площадь и на
-- безразмерный коэффициент; вся геометрия сидит в коэффициенте.
--
-- Допущения: поток несжимаем. Справедливо примерно до M < 0.3 (около
-- 100 м/с у земли). В игре скорости на порядок меньше, так что запас
-- десятикратный.
--------------------------------------------------------------------------------
function M.dynamic_pressure(rho, velocity)
	return 0.5 * rho * velocity * velocity
end

--------------------------------------------------------------------------------
-- Сила сопротивления
--------------------------------------------------------------------------------
--
--     D = 0.5 * Cd * rho * V^2 * A                                [Н]
--
-- Источник: NASA Glenn, «Modern Drag Equation» [nasa_drag_equation],
-- дословно «D = .5 * Cd * r * V^2 * A».
--
-- Единицы: [—]·[кг/м^3]·[м^2/с^2]·[м^2] = [кг·м/с^2] = [Н]. Сходится.
--
-- Допущения и границы:
--   * Cd берётся постоянным. На деле он зависит от числа Рейнольдса, числа
--     Маха и угла атаки. Для тупого тела вроде воксельного куба в диапазоне
--     Re 10^4...10^6 Cd действительно почти постоянен, так что для игры
--     допущение честное.
--   * Сопротивление направлено строго против вектора скорости относительно
--     воздуха. Боковая составляющая (side force) не моделируется.
--   * Ветра нет: скорость относительно воздуха равна скорости относительно
--     земли.
--
-- Почему квадратичный закон, а не линейный. Линейное сопротивление (закон
-- Стокса, D = 6*pi*mu*r*V) верно при Re << 1 — это пылинка в масле. Для тел
-- размером с метр на скоростях в метры в секунду Re порядка 10^5...10^6, где
-- сопротивление определяется срывом потока и растёт как квадрат скорости.
-- Линейную модель в игре брать нельзя: она даёт неверную предельную скорость
-- и неверную форму разгона. Сравнение обеих — experiments/19_damping.lua.
--------------------------------------------------------------------------------
function M.drag_force(cd, rho, velocity, area)
	return 0.5 * cd * rho * velocity * velocity * area
end

--------------------------------------------------------------------------------
-- Подъёмная сила
--------------------------------------------------------------------------------
--
--     L = 0.5 * Cl * rho * V^2 * S                                [Н]
--
-- Источник: NASA Glenn, «The Lift Equation» [nasa_lift_equation].
-- Единицы те же, что у сопротивления: [Н]. Сходится.
--
-- S — площадь крыла в плане (не сечение!), это разные площади у одного и
-- того же тела, и путаница между ними — классическая ошибка на порядок.
--------------------------------------------------------------------------------
function M.lift_force(cl, rho, velocity, wing_area)
	return 0.5 * cl * rho * velocity * velocity * wing_area
end

--------------------------------------------------------------------------------
-- Коэффициент подъёмной силы от угла атаки
--------------------------------------------------------------------------------
--
--     Cl = Cl_alpha * alpha           при |alpha| <= alpha_stall
--
-- Теория тонкого профиля даёт Cl_alpha = 2*pi на радиан [anderson_aero].
--
-- Единицы: alpha [рад], Cl_alpha [1/рад] → Cl безразмерен. Сходится.
--
-- Допущения:
--   * Линейность. Верна до срыва, дальше — нет.
--   * Бесконечное удлинение крыла. У реального крыла конечного размаха
--     наклон меньше из-за скоса потока от концевых вихрей:
--         a = a0 / (1 + a0 / (pi * e * AR)),  AR = b^2 / S
--     Поправка учтена в `finite_wing_lift_slope` и применяется явно.
--   * Несжимаемый поток.
--
-- Модель срыва здесь намеренно грубая: за критическим углом Cl спадает
-- линейно до половины пикового значения к удвоенному углу срыва. Настоящий
-- срыв — резкий, гистерезисный и зависит от профиля; воспроизводить его
-- в игре нет смысла, но обязательно нужно, чтобы за срывом подъёмная сила
-- ПАДАЛА, а не росла бесконечно, иначе игрок задирает нос и улетает вверх
-- на любой скорости. Это упрощение геймплейное и помечено как таковое.
--------------------------------------------------------------------------------
function M.lift_coefficient(alpha, cl_alpha, alpha_stall)
	cl_alpha = cl_alpha or C.value("cl_alpha_thin_airfoil")
	alpha_stall = alpha_stall or C.value("alpha_stall")

	local sign = alpha >= 0 and 1 or -1
	local size = math.abs(alpha)

	if size <= alpha_stall then
		return cl_alpha * alpha
	end

	local peak = cl_alpha * alpha_stall

	if size >= 2 * alpha_stall then
		return sign * peak * 0.5
	end

	-- Линейный спад от пика до половины пика
	local fade = (size - alpha_stall) / alpha_stall

	return sign * peak * (1 - 0.5 * fade)
end

--- Наклон линии подъёмной силы для крыла конечного удлинения, 1/рад.
---
---     a = a0 / (1 + a0 / (pi * e * AR))
---
--- e — коэффициент Освальда (0.7...0.9 у обычных крыльев, 1.0 у идеального
--- эллиптического). AR — удлинение, b^2/S. [anderson_aero]
---
--- Для воксельной машины это существенно: крыло из четырёх блоков имеет
--- удлинение около 1, и наклон падает почти вчетверо против 2*pi.
function M.finite_wing_lift_slope(a0, aspect_ratio, oswald)
	oswald = oswald or 0.8

	return a0 / (1 + a0 / (math.pi * oswald * aspect_ratio))
end

--------------------------------------------------------------------------------
-- Индуктивное сопротивление
--------------------------------------------------------------------------------
--
--     Cdi = Cl^2 / (pi * e * AR)
--
-- Плата за подъёмную силу: концевые вихри уносят энергию. Для крыла малого
-- удлинения — а у воксельной машины оно именно такое — это основная часть
-- сопротивления на малой скорости. Без него не получается характерная
-- «обратная сторона кривой потребной тяги», когда на малой скорости тяги
-- нужно БОЛЬШЕ. [anderson_aero]
--------------------------------------------------------------------------------
function M.induced_drag_coefficient(cl, aspect_ratio, oswald)
	oswald = oswald or 0.8

	return cl * cl / (math.pi * oswald * aspect_ratio)
end

--------------------------------------------------------------------------------
-- Предельная скорость
--------------------------------------------------------------------------------
--
--     V_t = sqrt(2*m*g / (Cd * rho * A))                         [м/с]
--
-- Источник: NASA Glenn, «Flight Equations with Drag»
-- [nasa_flight_equations_drag], дословно «V_t = sqrt(2*m*g/(Cd*r*A))».
--
-- Вывод: при установившемся падении сопротивление равно весу,
-- 0.5*Cd*rho*V^2*A = m*g, откуда V^2 = 2*m*g/(Cd*rho*A).
--
-- Единицы: [кг]·[м/с^2] / ([кг/м^3]·[м^2]) = [м^2/с^2], корень даёт [м/с].
-- Сходится.
--------------------------------------------------------------------------------
function M.terminal_velocity(mass, gravity, cd, rho, area)
	return math.sqrt(2 * mass * gravity / (cd * rho * area))
end

--------------------------------------------------------------------------------
-- Скорость сваливания
--------------------------------------------------------------------------------
--
--     V_stall = sqrt(2*m*g / (rho * S * Cl_max))                 [м/с]
--
-- Вывод: в горизонтальном полёте L = m*g. Подставляем уравнение подъёмной
-- силы с максимальным Cl и решаем относительно V. Ниже этой скорости
-- горизонтальный полёт невозможен ни при каком угле атаки.
--
-- Структурно совпадает с предельной скоростью — и это не совпадение: обе
-- получаются приравниванием аэродинамической силы к весу.
--------------------------------------------------------------------------------
function M.stall_speed(mass, gravity, rho, wing_area, cl_max)
	return math.sqrt(2 * mass * gravity / (rho * wing_area * cl_max))
end

--------------------------------------------------------------------------------
-- Установившийся координированный разворот
--------------------------------------------------------------------------------
--
-- Вывод (страница NASA о разворотах [nasa_banking_turns] качественная, поэтому
-- соотношения выводятся здесь из второго закона Ньютона):
--
-- В крене phi подъёмная сила L перпендикулярна плоскости крыльев. Раскладываем:
--     вертикаль:   L*cos(phi) = m*g          (высота постоянна)
--     горизонталь: L*sin(phi) = m*V^2 / R    (центростремительное ускорение)
--
-- Делим второе на первое:
--     tan(phi) = V^2 / (g*R)   →   R = V^2 / (g * tan(phi))      [м]
--
-- Из первого:
--     n = L / (m*g) = 1 / cos(phi)                                [—]
--
-- Угловая скорость разворота:
--     omega = V / R = g * tan(phi) / V                            [рад/с]
--
-- Перегрузка n подтверждается независимо: FAA PHAK, глава 5 [faa_phak].
--
-- Единицы R: [м^2/с^2] / [м/с^2] = [м]. Сходится.
-- Единицы omega: [м/с^2] / [м/с] = [1/с]. Сходится.
--
-- Допущения: разворот установившийся и координированный (без скольжения),
-- высота постоянна, тяги хватает на возросшее индуктивное сопротивление.
-- Крен 90 градусов даёт R = 0 и n = бесконечность — это не ошибка формулы,
-- а верное утверждение, что в чистом крене горизонтальный полёт невозможен.
--------------------------------------------------------------------------------
function M.load_factor(bank_angle)
	return 1 / math.cos(bank_angle)
end

function M.turn_radius(velocity, bank_angle, gravity)
	gravity = gravity or C.value("gravity")

	return velocity * velocity / (gravity * math.tan(bank_angle))
end

function M.turn_rate(velocity, bank_angle, gravity)
	gravity = gravity or C.value("gravity")

	return gravity * math.tan(bank_angle) / velocity
end

--- Рост скорости сваливания в развороте: V_s(n) = V_s * sqrt(n). [faa_phak]
function M.stall_speed_in_turn(stall_speed_level, bank_angle)
	return stall_speed_level * math.sqrt(M.load_factor(bank_angle))
end

--------------------------------------------------------------------------------
-- Плотность воздуха по высоте
--------------------------------------------------------------------------------
--
--     rho(h) = rho0 * exp(-h / H)
--
-- Изотермическое приближение с высотой однородной атмосферы H
-- [us_standard_atmosphere]. Реальная атмосфера не изотермична, но до 3 км
-- ошибка около процента, а игровые высоты и того меньше.
--------------------------------------------------------------------------------
function M.air_density(altitude)
	return C.value("rho_sea_level")
		* math.exp(-altitude / C.value("scale_height"))
end

--------------------------------------------------------------------------------
-- Исполняемая проверка размерностей
--------------------------------------------------------------------------------

--- Прогоняет те же формулы на размерных величинах. Ошибка сборки формулы
--- падает здесь, а не всплывает в игре наклоном не в ту сторону.
--- @return список проверок { name, ok, got, expected }
function M.dimension_selftest()
	local results = {}

	local function case(name, expression, expected)
		local ok, value = pcall(expression)

		results[#results + 1] = {
			name = name,
			ok = ok and U.same(value, expected),
			got = ok and tostring(value.d) or ("ошибка: " .. tostring(value)),
			expected = tostring(expected),
		}
	end

	local rho = U.Q(1.225, D.density)
	local v = U.Q(20, D.velocity)
	local area = U.Q(4, D.area)
	local mass = U.Q(500, D.mass)
	local g = U.Q(9.81, D.acceleration)
	local cd = U.Q(1.05, D.scalar)
	local cl = U.Q(0.8, D.scalar)

	case("скоростной напор q = rho*V^2/2",
		function() return U.Q(0.5) * rho * v ^ 2 end, D.pressure)

	case("сопротивление D = Cd*rho*V^2*A/2",
		function() return U.Q(0.5) * cd * rho * v ^ 2 * area end, D.force)

	case("подъёмная сила L = Cl*rho*V^2*S/2",
		function() return U.Q(0.5) * cl * rho * v ^ 2 * area end, D.force)

	case("предельная скорость sqrt(2mg/(Cd*rho*A))",
		function() return U.sqrt(U.Q(2) * mass * g / (cd * rho * area)) end,
		D.velocity)

	case("радиус разворота V^2/(g*tan(phi))",
		function() return v ^ 2 / g end, D.length)

	case("угловая скорость g*tan(phi)/V",
		function() return g / v end, D.angular_velocity)

	case("перегрузка L/(m*g) безразмерна",
		function()
			return (U.Q(0.5) * cl * rho * v ^ 2 * area) / (mass * g)
		end, D.scalar)

	case("работа сопротивления D*расстояние = энергия",
		function()
			return U.Q(0.5) * cd * rho * v ^ 2 * area * U.Q(10, D.length)
		end, D.energy)

	case("мощность потребной тяги D*V",
		function()
			return U.Q(0.5) * cd * rho * v ^ 2 * area * v
		end, D.power)

	return results
end

M.references = {
	drag = R.nasa_drag_equation,
	lift = R.nasa_lift_equation,
	terminal = R.nasa_flight_equations_drag,
	turns = R.nasa_banking_turns,
	airfoil = R.anderson_aero,
}

return M
