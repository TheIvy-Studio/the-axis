-- the Axis · physics lab · эксперимент 03
-- Сила сопротивления: сам закон, его размерность и масштабирование.

package.path = ((arg and arg[0] or ""):gsub("[^/\\]*$", "") .. "../?.lua;")
	.. package.path

local experiment = require("lab.experiment")
local aero = require("lab.aero")
local check = require("lab.check")
local C = require("lab.constants")
local R = require("lab.references")

return experiment.define {
	id = "03",
	name = "drag_force",
	title = "Сила сопротивления воздуха",

	question = [[
Как именно считается сопротивление, сходятся ли у формулы размерности и как
сила растёт со скоростью? Здесь проверяется только закон, без движения:
динамика падения — в эксперименте 04.]],

	model = [[
    D = 0.5 * Cd * rho * V^2 * A                             [Н]

Источник — NASA Glenn, «Modern Drag Equation», дословно «D = .5 * Cd * r *
V^2 * A» [nasa_drag_equation].

Разбор по множителям:
    0.5*rho*V^2 = q — скоростной напор [Па], кинетическая энергия единицы
                      объёма набегающего потока;
    A           — характерная площадь [м^2];
    Cd          — безразмерный коэффициент, в который спрятана вся геометрия,
                  вязкость и сжимаемость.

Размерность: [—]·[кг/м^3]·[м^2/с^2]·[м^2] = [кг·м/с^2] = [Н]. Сходится.

Масштабирование, которое отсюда следует:
    удвоение скорости      → сила в 4 раза      (V^2)
    удвоение площади       → сила в 2 раза      (A)
    мощность на преодоление D*V растёт как V^3

Последнее объясняет, почему у машины есть жёсткий потолок скорости: тяга
растёт линейно с числом двигателей, а потребная мощность — кубически.]],

	simplifications = [[
1. Cd постоянен. На деле он зависит от числа Рейнольдса, числа Маха и угла
   атаки. Для тупого тела (а воксельная машина именно такая) в диапазоне
   Re = 10^4...10^6 зависимость слабая, поэтому потеря невелика.
2. Сопротивление направлено строго против вектора скорости. Боковая сила при
   скольжении не моделируется — теряется сопротивление скольжению, из-за
   которого настоящая машина сама выравнивается по потоку.
3. Ветра нет: скорость относительно воздуха равна скорости относительно
   земли. Это заметное упрощение, но в Luanti ветра и нет.
4. Плотность берётся постоянной. На игровых высотах (сотни метров) изменение
   меньше 3 %, так что упрощение честное. Модель rho(h) в lab/aero.lua есть.]],

	references = { R.nasa_drag_equation, R.anderson_aero },

	params = {
		cd = { value = 1.05, note = "коэффициент сопротивления (куб гранью вперёд)" },
		rho = { value = 1.225, note = "плотность воздуха, кг/м^3" },
		area = { value = 4.0, note = "площадь миделя, м^2 (машина 2x2 блока)" },
		speed = { value = 20.0, note = "скорость, м/с" },
	},

	run = function(P, ctx)
		----------------------------------------------------------------------
		-- Исполняемая проверка размерностей
		----------------------------------------------------------------------
		print("Проверка размерностей (вычисляется на размерных величинах):")

		local dimension_results = aero.dimension_selftest()
		local dimension_ok = true

		for _, entry in ipairs(dimension_results) do
			print(("  %s %-42s [%s]")
				:format(entry.ok and "ОК  " or "СБОЙ", entry.name, entry.got))

			dimension_ok = dimension_ok and entry.ok
		end

		----------------------------------------------------------------------
		-- Значения
		----------------------------------------------------------------------
		local q = aero.dynamic_pressure(P.rho, P.speed)
		local drag = aero.drag_force(P.cd, P.rho, P.speed, P.area)

		print()
		print(("Скоростной напор q = 0.5*rho*V^2      = %.4f Па"):format(q))
		print(("Сила сопротивления D = q*Cd*A         = %.4f Н"):format(drag))
		print(("Потребная мощность P = D*V            = %.4f Вт"):format(drag * P.speed))

		----------------------------------------------------------------------
		-- Масштабирование
		----------------------------------------------------------------------
		local drag_double = aero.drag_force(P.cd, P.rho, P.speed * 2, P.area)
		local drag_area = aero.drag_force(P.cd, P.rho, P.speed, P.area * 2)

		print()
		print(("Удвоение скорости: %.4f → %.4f Н, отношение %.6f")
			:format(drag, drag_double, drag_double / drag))
		print(("Удвоение площади:  %.4f → %.4f Н, отношение %.6f")
			:format(drag, drag_area, drag_area / drag))

		----------------------------------------------------------------------
		-- Кривые
		----------------------------------------------------------------------
		local force_curve, power_curve = {}, {}

		for index = 0, 120 do
			local v = index * 0.5
			local d = aero.drag_force(P.cd, P.rho, v, P.area)

			force_curve[#force_curve + 1] = { v, d }
			power_curve[#power_curve + 1] = { v, d * v }
		end

		ctx.show({
			{ label = "сила D(V)", mark = "*", points = force_curve },
		}, {
			title = "Сопротивление растёт как квадрат скорости",
			xlabel = "скорость, м/с",
			ylabel = "сила, Н",
			height = 16,
		})

		ctx.show({
			{ label = "мощность D*V", mark = "*", points = power_curve },
		}, {
			title = "Потребная мощность растёт как куб скорости",
			xlabel = "скорость, м/с",
			ylabel = "мощность, Вт",
			height = 16,
		})

		----------------------------------------------------------------------
		-- Справочные коэффициенты
		----------------------------------------------------------------------
		print()
		print("Коэффициенты сопротивления для сравнения:")
		print(("  куб гранью вперёд        Cd = %.3f"):format(C.value("cd_cube")))
		print(("  плоская пластина         Cd = %.3f"):format(C.value("cd_flat_plate")))
		print("  обтекаемое тело          Cd = 0.04...0.10")
		print("  самолёт братьев Райт     Cd = 0.045  (значение с сайта NASA)")
		print()
		print("Вывод для игры: воксельная машина аэродинамически — кирпич.")
		print("Её Cd примерно в 20 раз хуже обтекаемого тела, и это физически")
		print("верно, а не недостаток модели.")

		ctx.save({
			{ label = "сила, Н", points = force_curve },
		}, {
			title = "Сопротивление в зависимости от скорости",
			xlabel = "скорость, м/с",
			ylabel = "сила, Н",
		}, {
			headers = { "v", "drag", "power" },
			rows = (function()
				local rows = {}

				for index, point in ipairs(force_curve) do
					rows[index] = { point[1], point[2], power_curve[index][2] }
				end

				return rows
			end)(),
		})

		----------------------------------------------------------------------
		local suite = check.new("сила сопротивления")

		suite:is_true("все размерности сходятся", dimension_ok,
			"проверка исполняемая: выражения собираются на величинах с "
			.. "размерностью, несогласованность бросает ошибку")

		suite:close("D = q * Cd * A",
			drag, q * P.cd * P.area, 1e-12,
			"тождество по определению скоростного напора; допуск — округление")

		suite:close("удвоение скорости даёт четырёхкратную силу",
			drag_double / drag, 4, 1e-12,
			"следствие квадратичной зависимости, точное отношение")

		suite:close("удвоение площади даёт двукратную силу",
			drag_area / drag, 2, 1e-12,
			"сила линейна по площади, точное отношение")

		suite:close("мощность растёт как куб скорости",
			aero.drag_force(P.cd, P.rho, P.speed * 2, P.area) * P.speed * 2
				/ (drag * P.speed),
			8, 1e-12,
			"V^2 от силы умножается ещё на V, итого V^3")

		suite:within("сопротивление положительно и конечно",
			drag, 1e-6, 1e9,
			"физический смысл: сила сопротивления не может быть ни нулевой "
			.. "при ненулевой скорости, ни бесконечной")

		return suite
	end,
}
